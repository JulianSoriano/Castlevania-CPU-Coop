# Builds stairs.inc: the game's own stair-endpoint table (bank 6) copied into the AI bank.
rom=open('/root/cv/orig.nes','rb').read()
b15=rom[16+15*0x4000:16+16*0x4000]; b6=rom[16+6*0x4000:16+7*0x4000]
ptrs=[b15[0xFBEC-0xC000+2*s]|b15[0xFBED-0xC000+2*s]<<8 for s in range(18)]
out=['; generated by gen_stairs.py: stair endpoint tables per stage (2 bytes each, 0 ends)']
out.append('st_ptr:')
for s,p in enumerate(ptrs): out.append(f'    .word stt_{p:04X}')
for p in sorted(set(ptrs)):
    d=[];y=0
    while b6[p-0x8000+y]!=0:
        d+= [b6[p-0x8000+y],b6[p-0x8000+y+1]]; y+=2
    d.append(0)
    out.append(f'stt_{p:04X}: .byte '+','.join(str(x) for x in d))
open('stairs.inc','w').write('\n'.join(out)+'\n')
print(len(out),sum(1 for p in set(ptrs)))
